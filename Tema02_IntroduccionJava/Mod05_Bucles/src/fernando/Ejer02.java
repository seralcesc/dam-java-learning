public class Ejer02 {

    public static void main(String[] args) {

        double temperatura, farenheit, kelvin;

        temperatura = 36.6;

        farenheit = temperatura * 9/5.0 + 32;
        kelvin = temperatura + 273.15;

        System.out.println(String.format("=== TEMPERATURA %.1fºC ===\n", temperatura));
        System.out.println(String.format("· FARENHEIT = %.2f", farenheit));
        System.out.println(String.format("· KELVIN = %.2f", kelvin));


    } // main

} // class